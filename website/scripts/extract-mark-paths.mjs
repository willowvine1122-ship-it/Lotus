#!/usr/bin/env node
/**
 * Extracts the Lotus mark's <path> data from an SVG into src/components/hero/mark-paths.ts,
 * so the 3D hero samples its points from the supplied logo file (never a redrawn one).
 *
 *   node scripts/extract-mark-paths.mjs public/brand/lotus-mark.svg
 *
 * When the full SVG logo set lands, point this at lotus-master-icon-colour.svg and re-run.
 * Parts are matched by fill color (brand book p.10, "Seven parts, seven solid fills").
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const file = process.argv[2] ?? "public/brand/lotus-mark.svg";
const svg = readFileSync(resolve(file), "utf8");

const viewBox = (svg.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 1280 1280").split(/[\s,]+/).map(Number);
const partByFill = {
  "#c8326a": "petal", "#f2b33d": "petal", "#ff6b4a": "petal", "#6a3fe0": "petal",
  "#4a1f45": "petalOverlap", "#c98a12": "petalOverlap", "#d9482a": "petalOverlap", "#3e1fa3": "petalOverlap",
  "#6e9598": "wSide", "#5dbe94": "wSide", "#74acf2": "wSide", "#d8ccff": "wSide",
  "#2f5a5f": "wCenter", "#22936b": "wCenter", "#1769c9": "wCenter", "#b7a4fa": "wCenter",
  "#1e454a": "wLeg", "#0f6e52": "wLeg", "#1556b0": "wLeg", "#9c82f5": "wLeg",
  "#0f2a2e": "wShadow", "#0a4a38": "wShadow", "#123c99": "wShadow", "#5530c4": "wShadow",
};

const paths = [];
const re = /<path\b([^>]*)\/?>/g;
let m;
while ((m = re.exec(svg))) {
  const attrs = m[1];
  const id = attrs.match(/\bid="([^"]+)"/)?.[1] ?? `path-${paths.length}`;
  const fill = (attrs.match(/\bfill="([^"]+)"/)?.[1] ?? "").toLowerCase();
  const d = attrs.match(/\bd="([^"]+)"/)?.[1];
  if (!d) continue;
  const part = partByFill[fill] ?? "petal";
  paths.push({ id, part, fill, d });
}
if (paths.length === 0) throw new Error(`No <path> elements found in ${file}`);

const out = `/* Generated by scripts/extract-mark-paths.mjs from ${file}. Do not edit by hand. */
export type MarkPart = "petal" | "petalOverlap" | "wSide" | "wCenter" | "wLeg" | "wShadow";

export interface MarkPath {
  id: string;
  part: MarkPart;
  fill: string;
  d: string;
}

/** SVG viewBox of the source file: [minX, minY, width, height]. */
export const MARK_VIEWBOX: readonly [number, number, number, number] = [${viewBox.join(", ")}];

/** Paths in SVG draw order (later paths paint over earlier ones). */
export const MARK_PATHS: readonly MarkPath[] = ${JSON.stringify(paths, null, 2)};
`;
writeFileSync(resolve("src/components/hero/mark-paths.ts"), out);
console.log(`Wrote ${paths.length} paths from ${file} (viewBox ${viewBox.join(" ")}) to src/components/hero/mark-paths.ts`);
